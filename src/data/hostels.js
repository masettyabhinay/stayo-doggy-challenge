// Helper to filter and rank hostels based on quiz profile
export function findMatchingHostels(personalityId, preferences) {
  return stayoHostels.map(h => {
    let score = h.matchScore;
    if (h.bestMatchedFor.includes(personalityId)) {
      score += 4;
    }
    // Budget alignment
    if (preferences.budget === "economy" || preferences.budget === "economy_range") {
      if (h.startingPrice <= 6000) score += 5;
    } else if (preferences.budget === "premium_range") {
      if (h.startingPrice >= 8000) score += 5;
    }
    return { ...h, dynamicMatch: Math.min(99, score) };
  }).sort((a, b) => b.dynamicMatch - a.dynamicMatch);
}
